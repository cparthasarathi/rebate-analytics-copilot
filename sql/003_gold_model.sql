-- Sanitized illustrative model; synthetic/example columns only.
CREATE TABLE IF NOT EXISTS REBATE_ANALYTICS.GOLD.DIM_PRODUCT (
    PRODUCT_KEY NUMBER(38,0) NOT NULL,
    PRODUCT_CODE VARCHAR(100) NOT NULL,
    PRODUCT_LABEL VARCHAR(200),
    IS_IN_POC_SCOPE BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS REBATE_ANALYTICS.GOLD.DIM_CONTRACT (
    CONTRACT_KEY NUMBER(38,0) NOT NULL,
    CONTRACT_REF_TOKEN VARCHAR(128) NOT NULL,
    EFFECTIVE_DATE DATE NOT NULL,
    EXPIRATION_DATE DATE,
    REBATE_RATE NUMBER(9,6),
    IS_CURRENT BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS REBATE_ANALYTICS.GOLD.DIM_CUSTOMER_PAYER (
    PAYER_KEY NUMBER(38,0) NOT NULL,
    PAYER_CODE VARCHAR(100) NOT NULL,
    PAYER_LABEL VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS REBATE_ANALYTICS.GOLD.DIM_PERIOD (
    PERIOD_KEY NUMBER(38,0) NOT NULL,
    PERIOD_MONTH DATE NOT NULL
);

-- Grain: one claim line reconciled to one contract version for one reporting period.
-- No patient name/ID, diagnosis, dosage, or clinical attribute belongs here.
CREATE TABLE IF NOT EXISTS REBATE_ANALYTICS.GOLD.FACT_REBATE_TRANSACTION (
    REBATE_FACT_KEY NUMBER(38,0) NOT NULL,
    SOURCE_CLAIM_REF_TOKEN VARCHAR(128) NOT NULL,
    PRODUCT_KEY NUMBER(38,0) NOT NULL,
    CONTRACT_KEY NUMBER(38,0) NOT NULL,
    PAYER_KEY NUMBER(38,0) NOT NULL,
    PERIOD_KEY NUMBER(38,0) NOT NULL,
    EXPECTED_AMOUNT NUMBER(14,2),
    CLAIMED_AMOUNT NUMBER(14,2),
    PAID_AMOUNT NUMBER(14,2),
    ADJUSTMENT_AMOUNT NUMBER(14,2),
    VARIANCE_AMOUNT NUMBER(14,2),
    LOAD_RUN_ID VARCHAR(100) NOT NULL,
    SOURCE_RECORD_HASH VARCHAR(64) NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

